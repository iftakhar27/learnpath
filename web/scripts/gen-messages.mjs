// Copies the student app's strings (mobile/lib/l10n/app_*.arb, the single source of English and Hindi text) into
// src/lib/i18n/messages.gen.ts. Run `npm run gen:messages` after editing the ARB files.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const load = (lang) => {
  const arb = JSON.parse(readFileSync(resolve(root, `../mobile/lib/l10n/app_${lang}.arb`), "utf8"));
  return Object.fromEntries(Object.entries(arb).filter(([k]) => !k.startsWith("@")));
};
const en = load("en");
const hi = load("hi");
const missing = Object.keys(en).filter((k) => !(k in hi));
if (missing.length) throw new Error(`Hindi is missing: ${missing.join(", ")}`);

const out = `// GENERATED by scripts/gen-messages.mjs from mobile/lib/l10n/app_*.arb — do not edit.
export const appMessages = ${JSON.stringify({ en, hi }, null, 2)} as const;
`;
writeFileSync(resolve(root, "src/lib/i18n/messages.gen.ts"), out);
console.log(`wrote src/lib/i18n/messages.gen.ts (${Object.keys(en).length} strings)`);
