// Generates lib/core/api/models.g.dart from the backend's OpenAPI spec.
//
//   dart run tool/gen_models.dart [path/to/openapi.json]
//
// Every schema becomes an immutable Dart class (or enum) with fromJson/toJson, so the app's models always match
// the API contract. Re-run after the backend contract changes (scripts/export-openapi.sh regenerates the spec).
import 'dart:convert';
import 'dart:io';

const _reserved = {
  'default',
  'class',
  'enum',
  'switch',
  'case',
  'is',
  'in',
  'new',
  'null',
  'true',
  'false',
  'var',
  'final',
  'const',
  'void',
  'with',
  'this',
  'super',
};

late Map<String, dynamic> _schemas;

void main(List<String> args) {
  final specPath = args.isNotEmpty ? args.first : '../docs/openapi.json';
  final spec = jsonDecode(File(specPath).readAsStringSync()) as Map<String, dynamic>;
  _schemas = (spec['components'] as Map<String, dynamic>)['schemas'] as Map<String, dynamic>;

  final out = StringBuffer()
    ..writeln('// GENERATED by tool/gen_models.dart from docs/openapi.json. Do not edit by hand.')
    ..writeln('// ignore_for_file: constant_identifier_names, prefer_const_constructors_in_immutables')
    ..writeln()
    ..writeln("import 'package:flutter/foundation.dart' show immutable;")
    ..writeln();

  final names = _schemas.keys.toList()..sort();
  for (final name in names) {
    final schema = _schemas[name] as Map<String, dynamic>;
    if (schema['enum'] != null) {
      _writeEnum(out, name, (schema['enum'] as List).cast<String>());
    } else if (schema['properties'] != null) {
      _writeClass(out, name, schema);
    }
  }

  final target = File('lib/core/api/models.g.dart');
  target.writeAsStringSync(out.toString());
  stdout.writeln('Wrote ${target.path} (${names.length} schemas)');
}

String _lowerFirst(String s) => s.isEmpty ? s : s[0].toLowerCase() + s.substring(1);
String _field(String name) => _reserved.contains(name) ? '${name}_' : name;

void _writeEnum(StringBuffer out, String name, List<String> values) {
  out.writeln('enum $name {');
  for (final v in values) {
    out.writeln("  ${_lowerFirst(v)}('$v'),");
  }
  out
    ..writeln('  ;')
    ..writeln()
    ..writeln('  const $name(this.wire);')
    ..writeln('  final String wire;')
    ..writeln()
    ..writeln('  static $name fromJson(String value) =>')
    ..writeln("      values.firstWhere((e) => e.wire == value, orElse: () => throw FormatException('Unknown $name: \$value'));")
    ..writeln()
    ..writeln('  String toJson() => wire;')
    ..writeln('}')
    ..writeln();
}

/// A property's Dart type plus how to read/write it.
class _Type {
  _Type(this.dart, this.read, this.write);
  final String dart;
  final String Function(String expr) read; // expr is a non-null JSON value
  final String Function(String expr) write; // expr is a non-null Dart value
}

_Type _typeOf(Map<String, dynamic> p) {
  final ref = p[r'$ref'] as String? ?? ((p['allOf'] as List?)?.first as Map<String, dynamic>?)?[r'$ref'] as String?;
  if (ref != null) {
    final name = ref.split('/').last;
    final isEnum = (_schemas[name] as Map<String, dynamic>)['enum'] != null;
    return isEnum
        ? _Type(name, (e) => '$name.fromJson($e as String)', (e) => '$e.toJson()')
        : _Type(name, (e) => '$name.fromJson($e as Map<String, dynamic>)', (e) => '$e.toJson()');
  }
  switch (p['type']) {
    case 'string':
      return p['format'] == 'date-time'
          ? _Type('DateTime', (e) => 'DateTime.parse($e as String)', (e) => '$e.toIso8601String()')
          : _Type('String', (e) => '$e as String', (e) => e);
    case 'integer':
      return _Type('int', (e) => '($e as num).toInt()', (e) => e);
    case 'number':
      return _Type('double', (e) => '($e as num).toDouble()', (e) => e);
    case 'boolean':
      return _Type('bool', (e) => '$e as bool', (e) => e);
    case 'array':
      final item = _typeOf(p['items'] as Map<String, dynamic>);
      return _Type(
        'List<${item.dart}>',
        (e) => '($e as List<dynamic>).map((x) => ${item.read('x')}).toList()',
        (e) => '$e.map((x) => ${item.write('x')}).toList()',
      );
    default:
      return _Type('Object', (e) => e, (e) => e);
  }
}

void _writeClass(StringBuffer out, String name, Map<String, dynamic> schema) {
  final props = (schema['properties'] as Map<String, dynamic>).cast<String, Map<String, dynamic>>();
  final required = ((schema['required'] as List?) ?? const []).cast<String>().toSet();
  final fields = [
    for (final e in props.entries)
      (json: e.key, dart: _field(e.key), type: _typeOf(e.value), nullable: !required.contains(e.key) || e.value['nullable'] == true),
  ];

  out
    ..writeln('@immutable')
    ..writeln('class $name {')
    ..writeln('  const $name({');
  for (final f in fields) {
    out.writeln('    ${f.nullable ? '' : 'required '}this.${f.dart},');
  }
  out.writeln('  });');
  out.writeln();
  out.writeln('  factory $name.fromJson(Map<String, dynamic> json) => $name(');
  for (final f in fields) {
    final value = "json['${f.json}']";
    out.writeln(f.nullable ? '        ${f.dart}: $value == null ? null : ${f.type.read(value)},' : '        ${f.dart}: ${f.type.read(value)},');
  }
  out.writeln('      );');
  out.writeln();
  for (final f in fields) {
    out.writeln('  final ${f.type.dart}${f.nullable ? '?' : ''} ${f.dart};');
  }
  out.writeln();
  out.writeln('  Map<String, dynamic> toJson() => {');
  for (final f in fields) {
    if (!f.nullable) {
      out.writeln("        '${f.json}': ${f.type.write(f.dart)},");
    } else {
      // Null-aware map entries omit the key when the value is null.
      final converted = f.type.write('${f.dart}?');
      out.writeln("        '${f.json}': ?${converted == '${f.dart}?' ? f.dart : converted},");
    }
  }
  out
    ..writeln('      };')
    ..writeln('}')
    ..writeln();
}
